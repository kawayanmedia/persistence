<?php

declare(strict_types=1);

namespace KawayanMedia\Persistence\Adapter;

use KawayanMedia\Persistence\Contract\DatabaseInterface;
use KawayanMedia\Persistence\Contract\LastInsertIdAwareInterface;
use KawayanMedia\Persistence\Exception\DatabaseException;
use KawayanMedia\Persistence\Sql\CompiledQuery;
use KawayanMedia\Persistence\Sql\Grammar;
use PDO;
use PDOException;
use PDOStatement;
use Throwable;

/**
 * PDO backed database. Works with any PDO driver; the generated SQL only uses
 * portable constructs (bare identifiers, positional placeholders).
 */
final class PdoDatabase implements DatabaseInterface, LastInsertIdAwareInterface
{
    private int $depth = 0;

    public function __construct(private readonly PDO $pdo)
    {
    }

    /**
     * @param array<int, mixed> $options
     */
    public static function fromDsn(string $dsn, ?string $username = null, ?string $password = null, array $options = []): self
    {
        $options += [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        ];

        try {
            $pdo = new PDO($dsn, $username, $password, $options);
        } catch (PDOException $exception) {
            throw DatabaseException::forQuery($dsn, $exception->getMessage(), $exception);
        }

        return new self($pdo);
    }

    public function pdo(): PDO
    {
        return $this->pdo;
    }

    /**
     * The id generated by the last insert, when the driver reports one.
     */
    public function lastInsertId(): int|string|null
    {
        $id = $this->pdo->lastInsertId();

        if ($id === false || $id === '' || $id === '0') {
            return null;
        }

        return ctype_digit((string) $id) ? (int) $id : $id;
    }

    public function select(string $table, array $columns = ['*'], array $conditions = [], array $options = []): array
    {
        return $this->run(Grammar::select($table, $columns, $conditions, $options))->fetchAll(PDO::FETCH_ASSOC);
    }

    public function count(string $table, array $conditions = []): int
    {
        $row = $this->run(Grammar::count($table, $conditions))->fetch(PDO::FETCH_ASSOC);

        return (int) (is_array($row) ? ($row['aggregate'] ?? 0) : 0);
    }

    public function insert(string $table, array $row): int
    {
        return $this->run(Grammar::insert($table, $row))->rowCount();
    }

    public function update(string $table, array $values, array $conditions = []): int
    {
        return $this->run(Grammar::update($table, $values, $conditions))->rowCount();
    }

    public function delete(string $table, array $conditions = []): int
    {
        return $this->run(Grammar::delete($table, $conditions))->rowCount();
    }

    public function transaction(callable $operation): mixed
    {
        if ($this->depth > 0) {
            return $operation($this);
        }

        try {
            $this->pdo->beginTransaction();
        } catch (PDOException $exception) {
            throw DatabaseException::forQuery('begin transaction', $exception->getMessage(), $exception);
        }

        $this->depth++;

        try {
            $result = $operation($this);
        } catch (Throwable $exception) {
            $this->depth--;

            if ($this->pdo->inTransaction()) {
                $this->pdo->rollBack();
            }

            throw $exception;
        }

        $this->depth--;
        $this->pdo->commit();

        return $result;
    }

    /**
     * Escape hatch for reporting queries the CRUD surface cannot express.
     *
     * @param list<mixed>|array<string, mixed> $parameters
     *
     * @return list<array<string, mixed>>
     */
    public function fetch(string $sql, array $parameters = []): array
    {
        return $this->run(new CompiledQuery($sql, array_values($parameters)))->fetchAll(PDO::FETCH_ASSOC);
    }

    /**
     * @param list<mixed>|array<string, mixed> $parameters
     */
    public function execute(string $sql, array $parameters = []): int
    {
        return $this->run(new CompiledQuery($sql, array_values($parameters)))->rowCount();
    }

    private function run(CompiledQuery $query): PDOStatement
    {
        try {
            $statement = $this->pdo->prepare($query->sql);

            if ($statement === false) {
                throw DatabaseException::forQuery($query->sql, $this->describe($this->pdo->errorInfo()));
            }

            $index = 1;

            foreach ($query->parameters as $value) {
                $statement->bindValue($index++, $value, self::parameterType($value));
            }

            if ($statement->execute() === false) {
                throw DatabaseException::forQuery($query->sql, $this->describe($statement->errorInfo()));
            }

            return $statement;
        } catch (PDOException $exception) {
            throw DatabaseException::forQuery($query->sql, $exception->getMessage(), $exception);
        }
    }

    private static function parameterType(mixed $value): int
    {
        return match (true) {
            is_int($value) => PDO::PARAM_INT,
            is_bool($value) => PDO::PARAM_BOOL,
            $value === null => PDO::PARAM_NULL,
            default => PDO::PARAM_STR,
        };
    }

    /**
     * @param array<int, mixed>|null $errorInfo
     */
    private function describe(?array $errorInfo): string
    {
        return is_array($errorInfo) && isset($errorInfo[2]) ? (string) $errorInfo[2] : 'unknown driver error';
    }
}
